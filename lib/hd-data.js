function parisDayKey(date = new Date()) {
  const parts = new Intl.DateTimeFormat("fr-CA", { timeZone: "Europe/Paris", year: "numeric", month: "2-digit", day: "2-digit" })
    .formatToParts(date).reduce((acc, part) => { acc[part.type] = part.value; return acc; }, {});
  return `${parts.year}-${parts.month}-${parts.day}`;
}
function dayIndexFromKey(key = "") {
  const match = String(key || "").match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return null;
  const year = Number(match[1]), month = Number(match[2]), day = Number(match[3]);
  const stamp = Date.UTC(year, month - 1, day);
  const check = new Date(stamp);
  if (check.getUTCFullYear() !== year || check.getUTCMonth() !== month - 1 || check.getUTCDate() !== day) return null;
  return Math.floor(stamp / 86400000);
}
function dailyIndex(date = new Date()) { return Math.abs(dayIndexFromKey(parisDayKey(date)) || 0); }
function dailyMystery(date = new Date()){ return mysteries[dailyIndex(date) % mysteries.length]; }
function dailyMysteryForKey(key = "") {
  const index = dayIndexFromKey(key);
  return index === null ? null : mysteries[Math.abs(index) % mysteries.length];
}
function mysteryById(id = "") { return mysteries.find(m => String(m.id) === String(id)) || null; }
